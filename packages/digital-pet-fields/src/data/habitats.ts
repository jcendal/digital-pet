// Classification is checked against the core catalog in tests. New species must
// receive an explicit assignment; Unknown is never an automatic catch-all.
export const HABITATS: Readonly<Record<FieldId, readonly string[]>> = Object.freeze(
  Object.fromEntries(
    FIELD_IDS.map((field) => [
      field,
      Object.freeze(
        [
          ...new Set([
            ...CURATED_HABITATS[field],
            ...Object.entries(reference)
              .filter(([, entry]) => entry.fields.includes(field))
              .map(([id]) => id),
            ...Object.entries(HABITAT_FALLBACKS)
              .filter(([, fields]) => (fields as readonly FieldId[]).includes(field))
              .map(([id]) => id),
          ]),
        ].sort(),
      ),
    ]),
  ) as Record<FieldId, readonly string[]>,
)
